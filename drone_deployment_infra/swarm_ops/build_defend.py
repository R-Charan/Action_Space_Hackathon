#!/usr/bin/env python3
"""Bake the sim's classical defender into swarm_defend.py, so the drones fly the exact code the sim scored.

Copies simulation_infra's tags/sensing.py, tello_defend/zone_pilot.py, face_geometry.py and
bus_pilot.py into the BAKED block of swarm_defend.py (imports rewritten to the baked module
names). Run it after changing any of them; `swarm_defend.py --selftest` fails while the baked
copy and the sim differ.

    python build_defend.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.join(HERE, "..", "..", "simulation_infra", "source", "action_space_kit", "action_space_kit")
TARGET = os.path.join(HERE, "swarm_defend.py")
BEGIN = "# >>> BAKED SIM: generated by build_defend.py from simulation_infra; edit the sim files, not this block\n"
END = "# <<< BAKED SIM\n"

# baked module name, sim source path (dependency order)
MODULES = [
    ("_baked_sensing", os.path.join(KIT, "tags", "sensing.py")),
    ("_baked_zone_pilot", os.path.join(KIT, "tasks", "direct", "tello_defend", "zone_pilot.py")),
    ("_baked_face_geometry", os.path.join(KIT, "tasks", "direct", "tello_defend", "face_geometry.py")),
    ("_baked_bus_pilot", os.path.join(KIT, "tasks", "direct", "tello_defend", "bus_pilot.py")),
]
IMPORTS = [
    (r"from action_space_kit\.tags\.sensing import", "from _baked_sensing import"),
    (r"from \.zone_pilot import", "from _baked_zone_pilot import"),
    (r"from \.face_geometry import", "from _baked_face_geometry import"),
]


def baked_sources():
    out = {}
    for name, path in MODULES:
        src = open(path).read()
        for pat, rep in IMPORTS:
            src = re.sub(pat, rep, src)
        if "'''" in src:
            sys.exit(f"{path} contains ''' : can't embed it as a raw string")
        left = [line for line in src.splitlines() if re.match(r"\s*from (\.|action_space_kit)", line)]
        if left:
            sys.exit(f"{path}: unhandled import {left}")
        out[name] = src
    return out


def block(sources):
    parts = [BEGIN, "BAKED = {}\n"]
    for name, src in sources.items():
        parts.append(f"BAKED[{name!r}] = r'''{src}'''\n")
    parts.append(END)
    return "".join(parts)


def main():
    text = open(TARGET).read()
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < 0:
        sys.exit(f"no BAKED SIM markers in {TARGET}")
    new = text[:i] + block(baked_sources()) + text[j + len(END):]
    if new == text:
        print("swarm_defend.py: baked sim already current")
        return
    open(TARGET, "w").write(new)
    print(f"swarm_defend.py: baked {', '.join(n for n, _ in MODULES)}")


if __name__ == "__main__":
    main()
